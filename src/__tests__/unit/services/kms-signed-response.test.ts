// Flow contract: a real ML-KEM response encrypts an actual compact JWS for the caller, signed by the selected provider's communication key; response-envelope issuer remains independent, and another provider or tampered payload cannot verify.
import {afterEach,expect,it} from '@jest/globals';
import {CryptographyService,Content} from 'antifraud-data-utils-ts/cryptography';
import {REPOSITORY_SAFE_EXAMPLES as safe} from 'sos-data-utils-ts/repository-privacy';
import {KmsService} from '../../../services/KmsService';
import {TenantsCacheManager} from '../../../managers/TenantsCacheManager';
import {VaultMemRepository} from '../../../database/repositories/vault/vault.mem.repository';
import {AdapterCryptoSdkNode} from '../../../gdc-backend-utils-node/adapters/node/crypto';
import {InMemoryEnvelopeAdapter} from '../../../services/kms-envelope-adapter';
import {InMemoryWrappedKeyRepository} from '../../../services/wrapped-key-repository';
const original={node:process.env.NODE_ENV,seed:process.env.DEV_SEED};
const services:KmsService[]=[];
afterEach(()=>{for(const service of services.splice(0))service.destroy();for(const [key,value] of [['NODE_ENV',original.node],['DEV_SEED',original.seed]]){if(value===undefined)delete process.env[key!];else process.env[key!]=value;}});
for(const sender of ['host',safe.tenantId])it(`signs and encrypts the response using the exact selected provider custody (${sender==='host'?'host':'tenant'})`,async()=>{
 process.env.NODE_ENV='development';process.env.DEV_SEED='true';
 const crypto=new CryptographyService(new AdapterCryptoSdkNode());
 let service:KmsService;
 const tenants=new TenantsCacheManager(new VaultMemRepository(),()=>service,safe.tenantId);
 service=new KmsService(crypto,tenants,{wrappedKeyRepository:new InMemoryWrappedKeyRepository(),envelopeAdapter:new InMemoryEnvelopeAdapter()});services.push(service);
 await service.init();await service.provisionKeys(safe.tenantId);
 const recipient=await crypto.generateKeyPairMlKem();
 const response={iss:`did:web:${safe.domain}`,aud:'did:web:controller.example.invalid',thid:'synthetic-response-thread',body:{data:[]}};
 const packed=await service.encodeResponse(response,[{...recipient.publicJWKey}],sender);
 const decrypted=await crypto.decryptJwe(packed,{...recipient.publicJWKey,dBytes:recipient.secretKeyBytes});
 expect(decrypted.protectedHeader).toMatchObject({cty:'JWS',kid:recipient.publicJWKey.kid});
 const compact=Content.bytesToStringUTF8(decrypted.decryptedBytes);
 expect(compact.split('.')).toHaveLength(3);
 const pinned=await service.getPublicVerificationKey(sender,undefined,'comm_sig');
 const other=await service.getPublicVerificationKey(sender==='host'?safe.tenantId:'host',undefined,'comm_sig');
 if(!pinned||!other)throw Error('Managed provider signing keys unavailable');
 expect(Content.base64UrlSafeToJSON(compact.split('.')[0]!)).toMatchObject({kid:pinned.kid,alg:'alg' in pinned?pinned.alg:undefined});
 expect(await crypto.verifyJws(compact,pinned)).toBe(true);
 expect(Content.base64UrlSafeToJSON(compact.split('.')[1]!)).toEqual(response);
 expect(await crypto.verifyJws(compact,other)).toBe(false);
 expect(await crypto.verifyJws([compact.split('.')[0],Content.objectToRawBase64UrlSafe({...response,aud:'did:web:other.example.invalid'}),compact.split('.')[2]].join('.'),pinned)).toBe(false);
 const vcKey=await service.getPublicVerificationKey(sender,undefined,'vc_sign');
 if(!vcKey)throw Error('Managed credential signing key unavailable');
 expect(await crypto.verifyJws(compact,vcKey)).toBe(false);
});
